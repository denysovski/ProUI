#!/usr/bin/env node
// Builds the effect catalogues from their data files.
//
//   effects/catalog/react-bits.json  ->  effects/catalog/react-bits.md
//   effects/catalog/21st-3d.json     ->  effects/catalog/21st-3d.md
//   effects/catalog/motion-primitives.json -> effects/catalog/motion-primitives.md
//   effects/catalog/aceternity.json  ->  effects/catalog/aceternity.md
//
// Usage: node scripts/build-effects.mjs [--check]   (run from the repository root, Node 18+)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const CHECK = process.argv.includes('--check');
const esc = (s = '') => String(s).replace(/\|/g, '\\|');
const NOTE = '<sub>Generated by `scripts/build-effects.mjs` from the JSON file next to this one. Edit the JSON, then run the script.</sub>';
const outputs = new Map();

// ---------- React Bits ----------
{
  const data = JSON.parse(readFileSync('effects/catalog/react-bits.json', 'utf8'));
  const order = ['Backgrounds', 'Animations', 'Text animations', 'Components', 'Micro'];
  const intro = {
    Backgrounds: 'Full-section animated backgrounds, mostly WebGL shaders. Use one per page, behind the hero or one feature.',
    Animations: 'Cursor effects, reveals, borders, transitions and interactive objects.',
    'Text animations': 'Animated headlines and text effects. One per page, on the headline that matters.',
    Components: 'Complete interactive components: galleries, carousels, cards, menus, docks.',
    Micro: 'Small interaction details for buttons, toggles, inputs, toasts and loaders.',
  };
  const flavour = (v) => (v.includes('TS-TW') ? 'TS-TW' : v[0]);
  const out = ['# React Bits catalogue', '',
    '> Every component in [React Bits](https://reactbits.dev/get-started/index), an open-source library of animated React components, with what it renders with and how to install it.', '',
    '[Effects library](../README.md) · [21st.dev 3D catalogue](21st-3d.md) · [Install guide](../install.md)', '',
    '> [!IMPORTANT]',
    '> React Bits is MIT with a Commons Clause: components may be used in any website or product, including paid ones, but must not be sold or redistributed on their own or in a bundle. ProUI therefore lists them and installs them into each project from the official registry; it does not copy their source into this repository.', '',
    '## Install', '', '```bash',
    '# one component (TypeScript + Tailwind flavour; also JS-CSS, JS-TW, TS-CSS)',
    'npx shadcn@latest add @react-bits/<Name>-TS-TW', '',
    '# or with jsrepo',
    'npx jsrepo@latest add https://reactbits.dev/r/<Name>-TS-TW', '```', '',
    'Add the registry once to `components.json`: `"registries": { "@react-bits": "https://reactbits.dev/r/{name}.json" }`.', '',
    '**Rendering:** `WebGL` needs a GPU canvas (heaviest, lazy-load it), `Canvas` is 2D canvas, `JS animation` uses GSAP or Motion, `CSS / DOM` is the lightest.', ''];
  out.push('## Contents', '', ...order.map((c) => `- [${c}](#${c.toLowerCase().replace(/ /g, '-')})`), '');
  for (const cat of order) {
    const items = data.filter((d) => d.category === cat).sort((a, b) => a.name.localeCompare(b.name));
    out.push(`## ${cat}`, '', intro[cat], '', '| Component | What it does | Renders with | Install |', '| --- | --- | --- | --- |');
    for (const c of items) {
      const deps = c.deps.filter((d) => !/hugeicons/.test(d));
      out.push(`| [${c.name}](${c.docs}) | ${esc(c.description)} | ${c.tech}${deps.length ? ` <sub>${deps.join(', ')}</sub>` : ''} | \`@react-bits/${c.name}-${flavour(c.variants)}\` |`);
    }
    out.push('');
  }
  out.push('---', '', NOTE, '');
  outputs.set('effects/catalog/react-bits.md', out.join('\n'));
}

// ---------- 21st.dev 3D ----------
{
  const data = JSON.parse(readFileSync('effects/catalog/21st-3d.json', 'utf8'));
  const order = ['Heroes and 3D scenes', 'Backgrounds', 'Globes', '3D objects and toys', 'Cards', 'Carousels and galleries', 'Scroll stories', 'Text and marquees', 'Buttons, menus, loaders and UI', 'Shader and developer tools'];
  for (const c of new Set(data.map((d) => d.category))) if (!order.includes(c)) order.push(c);
  const anchor = (c) => c.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-');
  const out = ['# 21st.dev 3D catalogue', '',
    `> Every component in the [21st.dev 3D collection](https://21st.dev/community/components/s/3d) (${data.length} components, read from the collection page), sorted by what it is for.`, '',
    '[Effects library](../README.md) · [React Bits catalogue](react-bits.md) · [Install guide](../install.md)', '',
    '> [!NOTE]',
    '> 21st.dev is a community registry: every component has its own author and licence. Downloading source needs a 21st.dev account, and a free account is limited to two component downloads per day; more needs a paid marketplace membership. ProUI keeps this index and installs only the components a project really uses. Check the licence column before shipping; "no licence" means ask the author first.', '',
    '## Install', '', '```bash',
    '# signed in to 21st.dev (or with the 21st.dev Magic MCP / "copy prompt" button)',
    'npx shadcn@latest add https://21st.dev/r/<author>/<component>', '```', '',
    'The `<author>/<component>` pair is the end of each link below.', '',
    '**Renders with:** `CSS 3D / SVG` (lightest), `Motion` or `GSAP` (JS animation), `Canvas`, `WebGL`, `WebGL (cobe)`, `Three.js`, `Three.js (R3F)`, `Spline` (heaviest).', ''];
  out.push('## Contents', '', ...order.map((c) => `- [${c}](#${anchor(c)})`), '');
  for (const cat of order) {
    const items = data.filter((d) => d.category === cat).sort((x, y) => x.name.localeCompare(y.name));
    out.push(`## ${cat}`, '', '| Component | Author | Use it for | Renders with | Licence |', '| --- | --- | --- | --- | --- |');
    for (const c of items) out.push(`| [${esc(c.name)}](${c.url}) | ${esc(c.author)} | ${esc(c.use)} | ${c.tech}${c.deps ? ` <sub>${esc(c.deps)}</sub>` : ''} | ${esc(c.license || 'not stated')} |`);
    out.push('');
  }
  out.push('---', '', NOTE, '');
  outputs.set('effects/catalog/21st-3d.md', out.join('\n'));
}

